"""progress_report.py - one-page PDF summary of a student's progress."""
import io
import time
from datetime import datetime


def build_pdf(user: str) -> bytes:
    """Return a PDF as bytes for the given user."""
    from reportlab.lib.pagesizes import A4
    from reportlab.lib.styles import getSampleStyleSheet, ParagraphStyle
    from reportlab.lib.units import cm
    from reportlab.lib import colors
    from reportlab.platypus import (SimpleDocTemplate, Paragraph, Spacer,
                                     Table, TableStyle)

    from app import history, flashcards
    from app.core import mistake_map, due

    buf = io.BytesIO()
    doc = SimpleDocTemplate(buf, pagesize=A4,
                            leftMargin=2 * cm, rightMargin=2 * cm,
                            topMargin=2 * cm, bottomMargin=2 * cm)
    styles = getSampleStyleSheet()
    title_style = ParagraphStyle("title", parent=styles["Title"], fontSize=22,
                                 textColor=colors.HexColor("#6366f1"))
    heading = ParagraphStyle("h", parent=styles["Heading2"],
                             textColor=colors.HexColor("#4f46e5"),
                             spaceBefore=14, spaceAfter=6)
    body = styles["BodyText"]

    story = []
    story.append(Paragraph("Lumen · Progress Report", title_style))
    story.append(Paragraph(f"Student: <b>{user}</b>", body))
    story.append(Paragraph(f"Generated: {datetime.now().strftime('%d %b %Y')}", body))
    story.append(Spacer(1, 0.5 * cm))

    counts = history.counts(user)
    n_right = counts["right"]
    n_wrong = counts["wrong"]
    acc = round(100 * n_right / (n_right + n_wrong)) if (n_right + n_wrong) else 0

    story.append(Paragraph("Summary", heading))
    summary = [
        ["Right answers", str(n_right)],
        ["Wrong answers", str(n_wrong)],
        ["Accuracy", f"{acc}%"],
    ]
    t1 = Table(summary, colWidths=[6 * cm, 4 * cm])
    t1.setStyle(TableStyle([
        ("BACKGROUND", (0, 0), (-1, -1), colors.HexColor("#f5f6ff")),
        ("BOX", (0, 0), (-1, -1), 0.5, colors.HexColor("#e5e7eb")),
        ("INNERGRID", (0, 0), (-1, -1), 0.25, colors.HexColor("#e5e7eb")),
        ("FONTNAME", (0, 0), (0, -1), "Helvetica-Bold"),
        ("LEFTPADDING", (0, 0), (-1, -1), 8),
        ("RIGHTPADDING", (0, 0), (-1, -1), 8),
        ("TOPPADDING", (0, 0), (-1, -1), 6),
        ("BOTTOMPADDING", (0, 0), (-1, -1), 6),
    ]))
    story.append(t1)

    rows = mistake_map(user)
    story.append(Paragraph("Misconceptions", heading))
    if not rows:
        story.append(Paragraph("No misconceptions recorded yet.", body))
    else:
        data = [["Misconception", "Errors", "Level (0–4)"]]
        for tag, errors, box in rows:
            display = tag.replace("_", " ").title()
            data.append([display, str(errors), f"{box}/4"])
        t2 = Table(data, colWidths=[8 * cm, 2.5 * cm, 3 * cm])
        t2.setStyle(TableStyle([
            ("BACKGROUND", (0, 0), (-1, 0), colors.HexColor("#6366f1")),
            ("TEXTCOLOR", (0, 0), (-1, 0), colors.white),
            ("FONTNAME", (0, 0), (-1, 0), "Helvetica-Bold"),
            ("BOX", (0, 0), (-1, -1), 0.5, colors.HexColor("#e5e7eb")),
            ("INNERGRID", (0, 0), (-1, -1), 0.25, colors.HexColor("#e5e7eb")),
            ("LEFTPADDING", (0, 0), (-1, -1), 8),
            ("RIGHTPADDING", (0, 0), (-1, -1), 8),
            ("TOPPADDING", (0, 0), (-1, -1), 6),
            ("BOTTOMPADDING", (0, 0), (-1, -1), 6),
        ]))
        story.append(t2)

    fc = flashcards.stats(user)
    story.append(Paragraph("Flashcards", heading))
    story.append(Paragraph(
        f"Total: <b>{fc['total']}</b> · Due: <b>{fc['due']}</b> · "
        f"Learned: <b>{fc['learned']}</b>", body))

    due_tags = due(user)
    story.append(Paragraph("Recommended next steps", heading))
    if due_tags:
        for tag in due_tags[:5]:
            story.append(Paragraph(
                f"• Review: <b>{tag.replace('_', ' ').title()}</b>", body))
    else:
        story.append(Paragraph("• Continue your current practice. No reviews due.",
                               body))

    story.append(Spacer(1, 1 * cm))
    story.append(Paragraph(
        "<i>Lumen verifies every correctness decision with symbolic mathematics. "
        "Explanations and translations are generated by language models.</i>",
        styles["Italic"]))

    doc.build(story)
    return buf.getvalue()